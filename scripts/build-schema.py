#!/usr/bin/env python3
"""Regenerates src/core/schema.ts from Zotero's schema.json.
Usage: python3 scripts/build-schema.py path/to/zotero-schema/schema.json
(https://github.com/zotero/zotero-schema)"""
import json, sys
s = json.load(open(sys.argv[1], encoding="utf-8"))
out = {}
for t in s["itemTypes"]:
    out[t["itemType"]] = {
        "fields": [f["field"] for f in t["fields"]],
        "base": {f["field"]: f["baseField"] for f in t["fields"] if "baseField" in f},
        "creators": [c["creatorType"] for c in t["creatorTypes"]],
    }
with open("src/core/schema.ts", "w", encoding="utf-8") as fh:
    fh.write("/* Generated by scripts/build-schema.py from zotero/zotero-schema (schema.json). */\n")
    fh.write("export const ITEM_TYPES: Record<string, { fields: string[]; base: Record<string, string>; creators: string[] }> = ")
    fh.write(json.dumps(out, indent="\t"))
    fh.write(""";

export function isValidField(itemType: string, field: string): boolean {
	return !!ITEM_TYPES[itemType]?.fields.includes(field);
}

/** "caseName" on a case -> "title"; fields without a base field map to themselves. */
export function baseField(itemType: string, field: string): string {
	return ITEM_TYPES[itemType]?.base[field] ?? field;
}

/** The field of `itemType` that holds `base` ("title" on a case -> "caseName"), or null. */
export function fieldForBase(itemType: string, base: string): string | null {
	const t = ITEM_TYPES[itemType];
	if (!t) return null;
	for (const [field, b] of Object.entries(t.base)) if (b === base) return field;
	return t.fields.includes(base) ? base : null;
}
""")
print("Wrote src/core/schema.ts")
